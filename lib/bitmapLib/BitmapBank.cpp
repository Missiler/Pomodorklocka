AssetData BitmapBank::getAsset(DisplayAsset id) {
    // Return format: { frames, totalFrames, fps, width, height }
    switch (id) {
        // Full Screen Assets (128x64)
        case DisplayAsset::TitlePage:   return { asset_TitlePage, 1, 0,  128, 64 };
        case DisplayAsset::LoadingAnim: return { asset_Loading,   2, 10, 128, 64 };
        
        // Small/Custom Assets
        case DisplayAsset::HeartIcon:   return { asset_Heart,     1, 0,  16,  16 };
        case DisplayAsset::CoinAnim:    return { asset_Coin,      4, 12, 8,   8  };

        //Side assets
        case DisplayAsset::Geyser:      return {asset_Geyser,     2,1, 16,64};
        case DisplayAsset::Kelp:        return {asset_Kelp,       2, 1,  16,  64 };
        case DisplayAsset::Seaweed:     return {asset_Seaweed,    2, 1,  16,  64 };
        case DisplayAsset::BigFrame:     return {asset_BigFrame,    1, 0,  16,  64 };
        case DisplayAsset::Hook:     return {asset_Hook,    4, 1,  16,  64 };
        case DisplayAsset::KelpV2:     return {asset_BigKelpV2,    2, 1,  16,  64 };
        case DisplayAsset::SeaweedV2:     return {asset_BigSeaweedV2,    2, 1,  16,  64 };






        //Main Menu Icons
        case DisplayAsset::VaultIcon:   return {asset_VaultIcon,  1, 0, 32, 16};
        case DisplayAsset::PlayIcon:    return {asset_playIcon,  1, 0, 32, 16};
        case DisplayAsset::SettingsIcon:return {asset_SettingsIcon,  1, 0, 32, 16};

        //Fish
        case DisplayAsset::AnglerFish: return {asset_AnglerFish, 1,0,24,24};
        case DisplayAsset::FrenchFish: return {asset_FrenchFish, 1,0,24,24};
        case DisplayAsset::ClassicFish: return {asset_ClassicFish, 1,0,24,24};
		case DisplayAsset::FishFrame: return {asset_FishFrame, 1,0,24,24};
		case DisplayAsset::BlueFish: return {asset_BlueFish, 1,0,24,24};
		case DisplayAsset::Manet: return {asset_Manet, 2,1,24,24};
		case DisplayAsset::SmolFish: return {asset_SmolFish, 1,0,24,24};
		case DisplayAsset::UpsideDownFish: return {asset_Uppochner, 2,1,24,24};
		case DisplayAsset::Turt: return {asset_Turtle, 1,0,24,24};

        //Small Side Assets
        case DisplayAsset::Sjogurka: return {asset_Sjogurka, 1,0,16,16};
        case DisplayAsset::SmallBuske: return {asset_Buske, 1,0,16,16};
        case DisplayAsset::SmallKorall: return {asset_SmallKorall, 1,0,16,16};
		case DisplayAsset::SmallKelp: return {asset_SmallKelp, 2,1,16,16};
		case DisplayAsset::SmallTree: return {asset_SmallTree, 1,0,16,16};
		case DisplayAsset::SmallKorallV2: return {asset_SmallKorallV2, 1,0,16,16};
		case DisplayAsset::SmallBlomma: return {asset_SmallBlomma, 1,0,16,16};
		case DisplayAsset::SmallFrame: return {asset_SmallFrame, 1,0,16,16};
		

        

        
        default:                        return { nullptr, 0, 0, 0, 0 };
    }
}