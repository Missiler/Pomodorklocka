void menu_manager::buttonAction(uint8_t button) {
    size_t stateIdx = static_cast<size_t>(currentState);
    
    if (currentState == MenuState::Startup) return; // Disallow startup escape inputs

    if (button == 1) {
        // Look up target based on current potentiometer selection item index
        if (menuPosition >= 0 && menuPosition < 3) {
            nextState = stateTable[stateIdx].button1Targets[menuPosition];
            
            // Add custom hooks for inline modifiers (optional adjustment space)
            if (currentState == MenuState::VolumeChange && menuPosition == 0) { /* Volume Up logic */ }
            if (currentState == MenuState::VolumeChange && menuPosition == 1) { /* Volume Down logic */ }
        }
    } 
    else if (button == 2) {
        // Universal back actions route cleanly out of the tracking definition row
        nextState = stateTable[stateIdx].button2Target;
    }
}